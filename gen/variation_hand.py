# ---------- shared LaTeX tidying for the tangent, variation and applications generators ----------
_ARG = r"((?:(?!\\right).)*?)"
def _arg(a):
    a = a.replace(" ", "")
    return a if _re.fullmatch(r"\d*[a-z]", a) else "(" + a + ")"
def fnpow(t):
    """Power of a function written on the function name: \\cos^{3}5x, \\ln^{2}x. Never \\ln x^{2}."""
    t = _re.sub(r"\\(ln|sin|cos|tan|cot)\{\\left\(" + _ARG + r" \\right\)\}\^\{(\d+)\}", lambda m: f"\\{m[1]}^{{{m[3]}}}{_arg(m[2])}", t)
    t = _re.sub(r"\\(sin|cos|tan|cot)\^\{(\d+)\}\{\\left\(" + _ARG + r" \\right\)\}", lambda m: f"\\{m[1]}^{{{m[2]}}}{_arg(m[3])}", t)
    t = _re.sub(r"(?:\\left)?\(\\(ln|sin|cos|tan|cot) (\d*[a-z])(?:\\right)?\)\^(?:\{(\d+)\}|(\d))", lambda m: f"\\{m[1]}^{{{m[3] or m[4]}}}{m[2]}", t)
    return t
def _split(t, sep):
    """Split at sep outside braces and \\left..\\right groups."""
    parts, depth, i, cur = [], 0, 0, ""
    while i < len(t):
        if t.startswith(sep, i) and depth == 0:
            parts.append(cur); cur = ""; i += len(sep); continue
        c = t[i]
        if c == "\\" and i + 1 < len(t) and not t.startswith(sep, i):
            cur += t[i:i+2]; i += 2; continue
        depth += (c == "{") - (c == "}")
        cur += c; i += 1
    parts.append(cur)
    return parts
def _norm(a):
    a = a.replace(" ", "").replace("\\left", "").replace("\\right", "")
    return _re.sub(r"\^\{(\w)\}", r"^\1", a)
def _dedup(t, sep):
    p = _split(t, sep); out = [p[0]]
    for q in p[1:]:
        if _norm(q) and _norm(q) == _norm(out[-1]): continue
        out.append(q)
    return sep.join(out)
def _leftn(m):
    pre, sg, n = m[1], m[2], m[3]
    if sg: return f"{pre}({sg}{n})"
    if pre and pre[-1] in ")}0123456789":
        return pre if n == "1" else f"{pre}\\cdot {n}"
    return pre + n
def _f1(m):
    a = m[1]
    return f"({a})" if _re.search(r"[+\-]", a[1:]) else a
def tidy_math(t):
    t = fnpow(t)
    t = t.replace("\\mathrm{IR}", "IR").replace("\\mathbb{R}", "IR")
    t = _re.sub(r"\\(leq|geq)(?=[a-zA-Z])", r"\\\1 ", t)
    t = _re.sub(r"\\le(?!ft|q|ss|f)(?=[a-zA-Z])", r"\\le ", t)
    t = _re.sub(r"\\ge(?!q)(?=[a-zA-Z])", r"\\ge ", t)
    t = _re.sub(r"\\(max|min)(?=[a-zA-Z])", r"\\\1 ", t)
    t = _re.sub(r"(?<![\w}])([a-z])\^\{(\d+)\}\^\{(\d+)\}", r"\\left(\1^{\2}\\right)^{\3}", t)
    t = _re.sub(r"\\frac\{([^{}]*)\}\{1\}", _f1, t)
    t = _re.sub(r"\\frac\{\\frac\{(\d+)\}\{(\d+)\}\}\{x\}", r"\\frac{\1}{\2x}", t)
    t = _re.sub(r"\+\\frac\{([^{}]*)\}\{-1\}", r"-\1", t)
    t = _re.sub(r"(?<![a-zA-Z\\'])\(x\)\^", "x^", t)
    t = _re.sub(r"(?<![\w\\)}'])\((\d+)\)\^", r"\1^", t)
    t = _re.sub(r"(^|.)\\left\((-?)(\d+)\\right\)(?!\^)", _leftn, t)
    t = _re.sub(r"(?<![\w'\)}])\(-1\)(?=[a-z(\\])", "-", t)
    t = _re.sub(r"(?<![\w'\)}])\(1\)(?=[a-z(\\])", "", t)
    t = _re.sub(r"(?<=[=({,])--", "", t)
    t = _re.sub(r"--", "+", t)
    t = _re.sub(r"\+\(-\s*([^()+\-]*)\)(?![\^a-zA-Z(\\])", lambda m: "-" + m[1].replace(" ", ""), t)
    t = t.replace("+-", "-")
    t = _re.sub(r"(?<![\d.\w}^_\\])1([a-z])(?![a-df-zA-Z]|e[a-zA-Z])", r"\1", t)
    t = _re.sub(r"(?<![\d.\w}^_\\])1(?=\\(?:ln|sin|cos|tan|sqrt)\b)", "", t)
    t = _re.sub(r"(\\le|\\leq|\\ge|\\geq) 1\|", r"\1 |", t)
    t = _re.sub(r"(?<=[\w)}'])\s*\+\s*0(?![\d.])(?![a-z\\^{])", "", t)
    if "\\begin" not in t:
        t = _dedup(t, "\\iff")
        t = "\\iff".join(_dedup(p, "=") for p in _split(t, "\\iff"))
    return t
def tidy(t):
    """Apply tidy_math to every formula of a Khmer text, or to a bare LaTeX string."""
    if "tikzpicture" in t: return t
    if "$" not in t: return tidy_math(t)
    t = _re.sub(r"\$\$(.+?)\$\$|\$([^$]+?)\$", lambda m: f"$${tidy_math(m[1])}$$" if m[1] is not None else f"${tidy_math(m[2])}$", t, flags=_re.S)
    return _re.sub(r"\$([^$]+)\$ (?:ឬ|នាំឱ្យ|នាំឲ្យ) \$\1\$", r"$\1$", t)
_LOCAL = _re.compile(r"(អតិបរមា|អប្បបរមា)(?!ធៀប)")
def local_words(t):
    return _LOCAL.sub(r"\1ធៀប", t)
def tidy_row(r, local=False):
    """Clean a finished row. local=True labels extrema as local (អតិបរមាធៀប, អប្បបរមាធៀប)."""
    for k in ("problem_km", "solution_km", "answer_latex"):
        r[k] = tidy(r[k])
        if local: r[k] = local_words(r[k])
    for d in r["diagrams"]:
        d["latex"] = tidy(d["latex"])
        if d.get("alt_km"):
            d["alt_km"] = tidy(d["alt_km"])
            if local: d["alt_km"] = local_words(d["alt_km"])
    r["marks"] = None
    return r
def boxed(sol):
    """Contents of every \\boxed{...} in a solution, in order."""
    out, i = [], 0
    while True:
        i = sol.find("\\boxed{", i)
        if i < 0: return out
        j = i + 7; d = 1
        while j < len(sol) and d:
            if sol[j] == "\\": j += 2; continue
            d += (sol[j] == "{") - (sol[j] == "}"); j += 1
        out.append(sol[i+7:j-1]); i = j

